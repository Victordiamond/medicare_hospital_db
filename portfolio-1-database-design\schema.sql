-- MediCare telemedicine platform practical
-- Fictional coursework examples only; no real patient data or medical advice.

CREATE TABLE IF NOT EXISTS patients (
    patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    date_of_birth DATE NOT NULL,
    sex VARCHAR(20),
    phone VARCHAR(30),
    email VARCHAR(254) UNIQUE,
    address TEXT,
    emergency_contact_name VARCHAR(160),
    emergency_contact_phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    specialization VARCHAR(120) NOT NULL,
    phone VARCHAR(30),
    email VARCHAR(254) UNIQUE,
    license_number VARCHAR(80) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE doctors ADD COLUMN IF NOT EXISTS offers_video_consultations BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS professional_bio TEXT;

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id),
    appointment_start TIMESTAMPTZ NOT NULL,
    appointment_end TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'confirmed', 'completed', 'cancelled', 'no_show')),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (appointment_end IS NULL OR appointment_end > appointment_start),
    UNIQUE (doctor_id, appointment_start)
);

-- Appointments represent bookable telemedicine consultations in this scenario.
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS consultation_mode VARCHAR(20) NOT NULL DEFAULT 'video'
    CHECK (consultation_mode IN ('video', 'in_person'));
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS meeting_reference VARCHAR(120);
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS symptoms_summary TEXT;

CREATE TABLE IF NOT EXISTS medical_records (
    medical_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id),
    appointment_id BIGINT REFERENCES appointments(appointment_id),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diagnosis TEXT NOT NULL,
    treatment_notes TEXT,
    follow_up_notes TEXT
);

CREATE TABLE IF NOT EXISTS prescriptions (
    prescription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medical_record_id BIGINT REFERENCES medical_records(medical_record_id),
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id),
    medication_name VARCHAR(160) NOT NULL,
    dosage VARCHAR(120) NOT NULL,
    frequency VARCHAR(120) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    instructions TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed', 'cancelled')),
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS billing (
    billing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    appointment_id BIGINT UNIQUE REFERENCES appointments(appointment_id),
    description TEXT NOT NULL,
    amount_due NUMERIC(12,2) NOT NULL CHECK (amount_due >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'NGN',
    status VARCHAR(20) NOT NULL DEFAULT 'unpaid'
        CHECK (status IN ('unpaid', 'partially_paid', 'paid', 'void')),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date DATE
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_id BIGINT NOT NULL REFERENCES billing(billing_id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN ('cash', 'card', 'bank_transfer', 'insurance', 'other')),
    payment_reference VARCHAR(120) UNIQUE,
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('pending', 'completed', 'failed', 'refunded'))
);

CREATE TABLE IF NOT EXISTS pharmacies (
    pharmacy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pharmacy_name VARCHAR(160) NOT NULL,
    address TEXT NOT NULL,
    latitude NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    phone VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (pharmacy_name, address)
);

CREATE TABLE IF NOT EXISTS pharmacy_fulfillments (
    fulfillment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL UNIQUE REFERENCES prescriptions(prescription_id),
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    pharmacy_id BIGINT NOT NULL REFERENCES pharmacies(pharmacy_id),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(24) NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested', 'accepted', 'ready_for_pickup', 'fulfilled', 'cancelled')),
    pickup_reference VARCHAR(80) UNIQUE
);

CREATE TABLE IF NOT EXISTS nurses (
    nurse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    specialty VARCHAR(120) NOT NULL,
    phone VARCHAR(30),
    email VARCHAR(254) UNIQUE,
    license_number VARCHAR(80) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS nurse_care_requests (
    care_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_reference VARCHAR(40) NOT NULL UNIQUE,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    prescription_id BIGINT NOT NULL REFERENCES prescriptions(prescription_id),
    nurse_id BIGINT NOT NULL REFERENCES nurses(nurse_id),
    planned_start_date DATE NOT NULL,
    planned_end_date DATE NOT NULL,
    visit_frequency VARCHAR(24) NOT NULL
        CHECK (visit_frequency IN ('once', 'daily', 'twice_daily', 'weekly', 'custom')),
    patient_request_notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested', 'accepted', 'active', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (planned_end_date >= planned_start_date)
);

CREATE TABLE IF NOT EXISTS nurse_visits (
    nurse_visit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_request_id BIGINT NOT NULL REFERENCES nurse_care_requests(care_request_id),
    nurse_id BIGINT NOT NULL REFERENCES nurses(nurse_id),
    visit_start TIMESTAMPTZ NOT NULL,
    visit_end TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'booked'
        CHECK (status IN ('booked', 'in_progress', 'completed', 'cancelled', 'no_show')),
    nurse_notes TEXT,
    CHECK (visit_end > visit_start),
    UNIQUE (nurse_id, visit_start)
);

CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments(patient_id);
