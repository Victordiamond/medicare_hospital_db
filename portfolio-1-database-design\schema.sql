-- Relational report: appointment, patient, doctor, record, prescription and balance.
SELECT
    a.appointment_start::date AS visit_date,
    p.first_name || ' ' || p.last_name AS patient,
    d.first_name || ' ' || d.last_name AS doctor,
    a.status AS appointment_status,
    mr.diagnosis,
    (SELECT string_agg(rx.medication_name, ', ')
       FROM prescriptions rx
      WHERE rx.medical_record_id = mr.medical_record_id) AS prescriptions,
    b.amount_due,
    COALESCE((SELECT SUM(py.amount)
                FROM payments py
               WHERE py.billing_id = b.billing_id
                 AND py.status = 'completed'), 0) AS paid_amount,
    GREATEST(b.amount_due - COALESCE((SELECT SUM(py.amount)
                                        FROM payments py
                                       WHERE py.billing_id = b.billing_id
                                         AND py.status = 'completed'), 0), 0) AS balance
FROM appointments a
JOIN patients p ON p.patient_id = a.patient_id
JOIN doctors d ON d.doctor_id = a.doctor_id
LEFT JOIN medical_records mr ON mr.appointment_id = a.appointment_id
LEFT JOIN billing b ON b.appointment_id = a.appointment_id
ORDER BY a.appointment_start;

-- Find the nearest active pharmacies to the supplied (fictional) map origin.
-- Replace origin_lat/origin_lon with a user's current map position at query time;
-- the sample schema does not persist precise patient location.
WITH origin AS (
    SELECT 6.524400::DOUBLE PRECISION AS lat, 3.379200::DOUBLE PRECISION AS lon
)
SELECT ph.pharmacy_name, ph.address, ph.phone,
       ROUND((6371 * 2 * ASIN(SQRT(LEAST(1.0,
           POWER(SIN(RADIANS(ph.latitude::DOUBLE PRECISION - o.lat) / 2), 2) +
           COS(RADIANS(o.lat)) * COS(RADIANS(ph.latitude::DOUBLE PRECISION)) *
           POWER(SIN(RADIANS(ph.longitude::DOUBLE PRECISION - o.lon) / 2), 2)
       ))))::NUMERIC, 2) AS distance_km
FROM pharmacies ph CROSS JOIN origin o
WHERE ph.is_active
ORDER BY distance_km
LIMIT 5;

-- Patient-facing nurse schedule with the related prescription (fictional example).
SELECT cr.request_reference, n.first_name || ' ' || n.last_name AS nurse,
       rx.medication_name, rx.dosage, rx.frequency AS prescribed_frequency,
       rx.instructions AS clinician_instructions, cr.visit_frequency AS nurse_visit_frequency,
       nv.visit_start, nv.visit_end, nv.status AS visit_status
FROM nurse_care_requests cr
JOIN nurses n ON n.nurse_id = cr.nurse_id
JOIN prescriptions rx ON rx.prescription_id = cr.prescription_id
LEFT JOIN nurse_visits nv ON nv.care_request_id = cr.care_request_id
WHERE cr.request_reference = 'DEMO-CARE-001'
ORDER BY nv.visit_start;

